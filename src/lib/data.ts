/**
 * Data hygiene pass: some seeded listings put language availability into the
 * `requirements` field (e.g. "Languages: English, Spanish"). Language
 * availability is not an eligibility requirement — move it into the real
 * `languages` tags and clear the requirements field.
 */
for (const r of RESOURCES) {
  const en = r.requirements?.en?.trim();
  if (!en) continue;
  const m = /^languages?\s*:\s*(.+)$/i.exec(en);
  if (!m) continue;
  const langs = m[1]
    .split(/[,/;&]| and /i)
    .map((s) => s.trim().toLowerCase())
    .filter(Boolean);
  const existing = new Set((r.languages ?? []).map((l) => l.toLowerCase()));
  r.languages = [...(r.languages ?? []), ...langs.filter((l) => !existing.has(l))];
  delete r.requirements;
}

